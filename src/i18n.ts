void i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources,
    // Hebrew is the default — English is opt-in via the language toggle.
    // No hardcoded `lng`: the detector reads the user's saved choice from
    // localStorage so EN persists across reloads; with nothing saved it
    // falls back to Hebrew. Browser language is intentionally not consulted.
    fallbackLng: 'he',
    supportedLngs: ['he', 'en'],
    interpolation: { escapeValue: false },
    detection: {
      order: ['localStorage'],
      caches: ['localStorage'],
      lookupLocalStorage: 'wbpl_lang',
    },
  });

// Apply RTL/LTR direction on language change
const applyDir = (lng: string) => {
  document.documentElement.setAttribute('dir', lng === 'he' ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', lng);
};
applyDir(i18n.language || 'he');
i18n.on('languageChanged', applyDir);

export default i18n;
